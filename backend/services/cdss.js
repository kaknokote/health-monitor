/**
 *
 * @param {string} metric   — 'heart_rate' | 'spo2' | 'temperature'
 * @param {number} value    — фактическое значение
 * @returns {object|null}   — объект рекомендации или null
 */
export function getRecommendation(metric, value) {
  let rules;
  if (metric === "heart_rate") rules = HEART_RATE_RULES;
  else if (metric === "spo2") rules = SPO2_RULES;
  else if (metric === "temperature") rules = TEMPERATURE_RULES;
  else return null;

  for (const rule of rules) {
    if (rule.check(value)) {
      return {
        name: rule.name,
        doctor: rule.doctor,
        reason: rule.reason,
        urgency: rule.urgency,
        clinical_note: rule.note,
        severity: rule.severity,
      };
    }
  }
  return null;
}
